"""Build item artwork locally, then explicitly publish the immutable files through existing S3 storage."""

from __future__ import annotations

import argparse
import asyncio
import hashlib
import json
import os
import shutil
import subprocess
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from src.backend.features.generation_ai.asset_storage import S3GeneratedAssetStorage
    from src.backend.features.items.dto.visuals import ItemVisualRenditionDTO

ROOT = Path(__file__).resolve().parents[2]
RENDERS = ROOT / "assets/item_art/renders"
DEFINITIONS = ROOT / "src/backend/features/items/resources/visuals/sword_renders.py"


def build(*, node: str, sharp_module: str | None = None) -> int:
    from src.backend.features.items.resources.visuals.sword import SWORD_VISUAL_SET

    payload = {
        "root": str(ROOT),
        "output": str(RENDERS),
        "variants": [variant.model_dump(mode="json") for variant in SWORD_VISUAL_SET.variants],
    }
    env = os.environ.copy()
    if sharp_module:
        env["ITEM_ART_SHARP_MODULE"] = sharp_module
    result = subprocess.run(
        [node, str(ROOT / "tools/assets/render_item_visuals.mjs")],
        input=json.dumps(payload),
        capture_output=True,
        text=True,
        encoding="utf-8",
        env=env,
        check=True,
    )
    rendered = json.loads(result.stdout)
    source = (
        '"""Content-addressed sword renditions. Generated by tools/assets/item_visuals.py build."""\n\n'
        + "SWORD_RENDERS = "
        + json.dumps(rendered, indent=4, ensure_ascii=False, sort_keys=True)
        + "\n"
    )
    DEFINITIONS.write_text(source, encoding="utf-8")
    return sum(len(renditions) for renditions in rendered.values())


def rendition_files() -> list[tuple[Path, ItemVisualRenditionDTO]]:
    from src.backend.features.items.resources.visuals import ITEM_VISUAL_CATALOG

    result = []
    for variant in ITEM_VISUAL_CATALOG.variants_by_id.values():
        for rendition in (variant.thumbnail, variant.image):
            if rendition is None:
                raise ValueError(f"Missing built rendition: {variant.visual_variant_id}")
            path = RENDERS / rendition.storage_key
            if not path.is_file() or hashlib.sha256(path.read_bytes()).hexdigest() != rendition.sha256:
                raise ValueError(f"Build artifact missing or does not match catalog: {variant.visual_variant_id}")
            result.append((path, rendition))
    return result


async def publish(storage: S3GeneratedAssetStorage, *, dry_run: bool = False) -> dict[str, int]:
    uploaded = 0
    skipped = 0
    files = rendition_files()
    for path, rendition in files:
        if dry_run or await storage.exists(rendition.storage_key):
            skipped += 1
            continue
        await storage.put_bytes(
            storage_key=rendition.storage_key,
            content=path.read_bytes(),
            content_type=rendition.content_type,
            metadata={"domain": "items", "sha256": rendition.sha256},
        )
        uploaded += 1
    return {"total": len(files), "uploaded": uploaded, "skipped": skipped}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("build", "publish"))
    parser.add_argument("--node", default=shutil.which("node"))
    parser.add_argument("--sharp-module")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    if args.action == "build":
        if not args.node:
            parser.error("Node.js path is required for SVG rasterization")
        print(f"Built {build(node=args.node, sharp_module=args.sharp_module)} item renditions")
        return
    if args.dry_run:
        count = len(rendition_files())
        print(json.dumps({"total": count, "uploaded": 0, "skipped": count}, sort_keys=True))
        return
    from src.backend.config.settings import settings
    from src.backend.features.generation_ai.asset_storage import S3GeneratedAssetStorage, build_s3_client

    # Dry run verifies local artifacts only; it must not open a network connection.
    storage = S3GeneratedAssetStorage(
        bucket=str(settings.asset_s3_bucket or ""),
        public_base_url=settings.asset_public_base_url,
        client=None if args.dry_run else build_s3_client(settings),
    )
    if not args.dry_run and not settings.asset_s3_bucket:
        parser.error("S3 bucket is not configured")
    print(json.dumps(asyncio.run(publish(storage, dry_run=args.dry_run)), sort_keys=True))


if __name__ == "__main__":
    main()
